import React, { useState } from 'react';
import { TradeSignal } from '../types';
import {
  TrendingUp,
  TrendingDown,
  ShieldAlert,
  Target,
  Clock,
  Zap,
  CheckCircle2,
  Copy,
  BellRing,
  HelpCircle,
  AlertTriangle,
} from 'lucide-react';
import { soundManager } from '../services/soundService';

interface SignalCardProps {
  type: 'SCALPING' | 'INTRADAY';
  signal: TradeSignal;
  currentPrice: number;
  onArmAlerts: (signal: TradeSignal, type: 'SCALPING' | 'INTRADAY') => void;
  isAlertActive?: boolean;
}

export const SignalCard: React.FC<SignalCardProps> = ({
  type,
  signal,
  currentPrice,
  onArmAlerts,
  isAlertActive = false,
}) => {
  const [copied, setCopied] = useState(false);

  // Extract numerical values
  const parseNum = (val?: string) => {
    if (!val) return null;
    const n = parseFloat(val.replace(/[^0-9.]/g, ''));
    return isNaN(n) ? null : n;
  };

  const sl = parseNum(signal.stopLoss);
  const tp1 = parseNum(signal.takeProfit1);
  const tp2 = parseNum(signal.takeProfit2);
  const tp3 = parseNum(signal.takeProfit3);

  // Parse entry zone mid price
  const entryParts = signal.entryZone.split('-').map((p) => parseNum(p.trim())).filter(Boolean) as number[];
  const midEntry = entryParts.length === 2 ? (entryParts[0] + entryParts[1]) / 2 : entryParts[0] || currentPrice;

  // Calculate distance from current price to entry
  const distanceToEntry = Math.abs(currentPrice - midEntry);
  const isNearEntry = distanceToEntry <= (type === 'SCALPING' ? 0.8 : 2.0);

  // Calculate distance to SL and TP1
  const slDistance = sl ? Math.abs(currentPrice - sl) : null;
  const tp1Distance = tp1 ? Math.abs(currentPrice - tp1) : null;

  const isBuy = signal.action === 'BUY';
  const isSell = signal.action === 'SELL';

  const handleCopy = () => {
    soundManager.playBlip();
    const text = `🔔 [XAU/USD ${type} SETUP]
Aksi: ${signal.action}
Timeframe: ${signal.timeframe}
Entry Zone: ${signal.entryZone}
Stop Loss: ${signal.stopLoss}
Take Profit 1: ${signal.takeProfit1}
Take Profit 2: ${signal.takeProfit2}
Take Profit 3: ${signal.takeProfit3}
Risk/Reward: ${signal.riskReward}
Trigger: ${signal.trigger}
Generated by AuraGold AI`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div
      className={`relative flex flex-col bg-slate-900/90 border rounded-xl overflow-hidden transition-all duration-300 shadow-xl ${
        isNearEntry
          ? 'border-amber-500/70 shadow-amber-500/10 ring-1 ring-amber-500/30'
          : 'border-slate-800 hover:border-slate-700'
      }`}
    >
      {/* Top Banner if price is in active zone */}
      {isNearEntry && (
        <div className="bg-amber-500/20 border-b border-amber-500/30 px-3 py-1 flex items-center justify-between text-xs text-amber-300 animate-pulse font-medium">
          <span className="flex items-center gap-1.5">
            <Zap className="w-3.5 h-3.5 fill-amber-400 text-amber-400" />
            HARGA BERADA DI AREA ENTRY ({distanceToEntry.toFixed(2)}$ / {(distanceToEntry * 10).toFixed(0)} pips)
          </span>
          <span className="font-mono text-[11px] bg-amber-500/30 px-1.5 py-0.5 rounded">SIAGA EKSEKUSI</span>
        </div>
      )}

      {/* Card Header */}
      <div className="p-4 border-b border-slate-800/80 flex items-center justify-between">
        <div className="flex items-center gap-2.5">
          <div
            className={`w-9 h-9 rounded-lg flex items-center justify-center font-bold text-sm shadow-md ${
              type === 'SCALPING'
                ? 'bg-gradient-to-br from-amber-500 to-yellow-600 text-slate-950'
                : 'bg-gradient-to-br from-blue-600 to-indigo-700 text-white'
            }`}
          >
            {type === 'SCALPING' ? <Zap className="w-5 h-5" /> : <Clock className="w-5 h-5" />}
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h3 className="text-white font-bold text-sm tracking-wide">
                {type === 'SCALPING' ? 'Scalping Setup' : 'Intraday Setup'}
              </h3>
              <span className="text-[11px] font-mono px-2 py-0.5 rounded bg-slate-800 text-slate-300 border border-slate-700">
                {signal.timeframe}
              </span>
            </div>
            <p className="text-[11px] text-slate-400 flex items-center gap-1 mt-0.5">
              <span>Durasi: {signal.duration}</span>
              <span>•</span>
              <span className="text-amber-400/90 font-mono">R:R {signal.riskReward}</span>
            </p>
          </div>
        </div>

        {/* Action Badge */}
        <div className="flex flex-col items-end">
          <div
            className={`px-3 py-1 rounded-lg font-bold text-sm tracking-wider flex items-center gap-1.5 shadow-lg ${
              isBuy
                ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/40 shadow-emerald-500/10'
                : isSell
                ? 'bg-rose-500/20 text-rose-400 border border-rose-500/40 shadow-rose-500/10'
                : 'bg-slate-700/50 text-slate-300 border border-slate-600'
            }`}
          >
            {isBuy && <TrendingUp className="w-4 h-4" />}
            {isSell && <TrendingDown className="w-4 h-4" />}
            <span>{signal.action}</span>
          </div>
          <span className="text-[10px] text-slate-400 mt-1 font-mono">
            Confidence: <strong className="text-slate-200">{signal.confidence}%</strong>
          </span>
        </div>
      </div>

      {/* Main Parameters Grid */}
      <div className="p-4 grid grid-cols-2 gap-3 text-xs">
        {/* Entry Zone */}
        <div className="col-span-2 bg-slate-950/70 p-3 rounded-lg border border-slate-800/80">
          <div className="flex items-center justify-between text-slate-400 mb-1">
            <span className="flex items-center gap-1 font-medium">
              <Target className="w-3.5 h-3.5 text-amber-400" />
              ZONA ENTRY
            </span>
            <span className="text-[11px] font-mono text-slate-400">
              Jarak: {(distanceToEntry * 10).toFixed(1)} pips
            </span>
          </div>
          <div className="text-base font-bold font-mono text-amber-400 flex items-center justify-between">
            <span>${signal.entryZone}</span>
            <span className="text-[11px] text-slate-500 font-normal">
              Live: ${currentPrice.toFixed(2)}
            </span>
          </div>
        </div>

        {/* Stop Loss */}
        <div className="bg-rose-950/20 p-3 rounded-lg border border-rose-500/20">
          <div className="flex items-center justify-between text-rose-400/90 mb-1">
            <span className="flex items-center gap-1 font-medium">
              <ShieldAlert className="w-3.5 h-3.5 text-rose-400" />
              STOP LOSS (SL)
            </span>
          </div>
          <div className="text-sm font-bold font-mono text-rose-400">
            ${signal.stopLoss}
          </div>
          {slDistance !== null && (
            <div className="text-[10px] font-mono text-rose-400/70 mt-1">
              {(slDistance * 10).toFixed(0)} pips ({slDistance.toFixed(2)}$)
            </div>
          )}
        </div>

        {/* Take Profit 1 */}
        <div className="bg-emerald-950/20 p-3 rounded-lg border border-emerald-500/20">
          <div className="flex items-center justify-between text-emerald-400/90 mb-1">
            <span className="flex items-center gap-1 font-medium">
              <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
              TARGET TP 1
            </span>
          </div>
          <div className="text-sm font-bold font-mono text-emerald-400">
            ${signal.takeProfit1}
          </div>
          {tp1Distance !== null && (
            <div className="text-[10px] font-mono text-emerald-400/70 mt-1">
              {(tp1Distance * 10).toFixed(0)} pips ({tp1Distance.toFixed(2)}$)
            </div>
          )}
        </div>

        {/* Take Profit 2 & 3 */}
        <div className="bg-slate-950/50 p-2.5 rounded-lg border border-slate-800">
          <div className="text-[11px] text-slate-400 mb-0.5">TARGET TP 2</div>
          <div className="text-xs font-bold font-mono text-emerald-400/90">
            ${signal.takeProfit2}
          </div>
        </div>

        <div className="bg-slate-950/50 p-2.5 rounded-lg border border-slate-800">
          <div className="text-[11px] text-slate-400 mb-0.5">RUNNER TP 3</div>
          <div className="text-xs font-bold font-mono text-emerald-400/90">
            ${signal.takeProfit3}
          </div>
        </div>
      </div>

      {/* Trigger & Risk Management Notes */}
      <div className="px-4 pb-3 space-y-2 text-xs">
        <div className="bg-slate-950/80 p-2.5 rounded-lg border border-slate-800/80">
          <div className="text-slate-400 font-medium mb-1 flex items-center gap-1 text-[11px]">
            <HelpCircle className="w-3 h-3 text-sky-400" />
            Alasan Trigger Sinyal:
          </div>
          <p className="text-slate-300 text-[11px] leading-relaxed">
            {signal.trigger}
          </p>
        </div>

        <div className="bg-amber-500/5 p-2 rounded border border-amber-500/10 text-[11px] text-amber-300/80 flex items-start gap-1.5">
          <AlertTriangle className="w-3.5 h-3.5 text-amber-400 shrink-0 mt-0.5" />
          <span>{signal.tip}</span>
        </div>
      </div>

      {/* Bottom Action Buttons */}
      <div className="p-3 bg-slate-950/60 border-t border-slate-800 flex items-center justify-between gap-2">
        <button
          onClick={() => onArmAlerts(signal, type)}
          className={`flex-1 flex items-center justify-center gap-1.5 py-2 px-3 rounded-lg text-xs font-semibold transition-all ${
            isAlertActive
              ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40'
              : 'bg-amber-500 text-slate-950 hover:bg-amber-400 active:scale-98'
          }`}
        >
          <BellRing className={`w-3.5 h-3.5 ${isAlertActive ? 'text-emerald-400 animate-bounce' : ''}`} />
          <span>{isAlertActive ? 'Alert Setup Aktif' : 'Pasang Alert Otomatis'}</span>
        </button>

        <button
          onClick={handleCopy}
          className="flex items-center gap-1.5 py-2 px-3 bg-slate-800 hover:bg-slate-700 text-slate-200 rounded-lg text-xs font-medium border border-slate-700 transition-all active:scale-98"
          title="Salin parameter sinyal untuk MT4/MT5/Telegram"
        >
          {copied ? <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
          <span>{copied ? 'Tersalin!' : 'Copy'}</span>
        </button>
      </div>
    </div>
  );
};
